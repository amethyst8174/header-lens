const require = createRequire(import.meta.url);
const src = process.argv[2];
if (!src) { console.error("usage: node tools/build-data.mjs <source-dir>"); process.exit(1); }
const out = path.join(path.dirname(new URL(import.meta.url).pathname), "..", "data");
fs.mkdirSync(out, { recursive: true });
const read = (f) => fs.readFileSync(path.join(src, f), "utf8");
const has = (f) => fs.existsSync(path.join(src, f));
const today = new Date().toISOString().slice(0, 10);

// ---------- IP ranges -> compact sorted tables ----------
// IPv6 is keyed on the top 48 bits (/48), which is enough for allocation-level lookups
// and keeps every key below 2^53 so the browser can use plain numbers.
const TOP = 1n << 48n;
function key(s, v6) {
  if (!v6) return BigInt(s);
  return BigInt(s) >> 80n;
}

// Rows -> [starts[], values[]] with explicit gap rows (value 0) so lookups never over-match.
function table(text, v6, valueOf) {
  const starts = [], vals = [];
  let prevEnd = -1n;
  for (const line of text.split("\n")) {
    if (!line || line[0] === "#") continue;
    const i1 = line.indexOf(","), i2 = line.indexOf(",", i1 + 1);
    const a = key(line.slice(0, i1), v6), b = key(line.slice(i1 + 1, i2), v6);
    const v = valueOf(line.slice(i2 + 1));
    if (a > prevEnd + 1n) { starts.push(prevEnd + 1n); vals.push(0); }
    else if (a <= prevEnd) { // overlap after truncation to /64: keep the first owner
      if (b <= prevEnd) continue;
    }
    const s = a <= prevEnd ? prevEnd + 1n : a;
    if (vals.length && vals[vals.length - 1] === v && starts.length) { prevEnd = b; continue; }
    starts.push(s); vals.push(v); prevEnd = b;
  }
  const max = v6 ? TOP - 1n : 0xffffffffn;
  if (prevEnd < max) { starts.push(prevEnd + 1n); vals.push(0); }
  if (starts[0] !== 0n) { starts.unshift(0n); vals.unshift(0); }
  return { starts, vals };
}

const ccList = [""];
const ccIndex = new Map();
const ccOf = (c) => {
  c = c.trim().toUpperCase();
  if (!/^[A-Z]{2}$/.test(c)) return 0;
  if (!ccIndex.has(c)) { ccIndex.set(c, ccList.length); ccList.push(c); }
  return ccIndex.get(c);
};
const asnList = [[0, ""]];
const asnIndex = new Map();
const asnOf = (rest) => {
  const j = rest.indexOf(",");
  const num = Number(j === -1 ? rest : rest.slice(0, j));
  const name = (j === -1 ? "" : rest.slice(j + 1)).replace(/^"|"$/g, "").trim();
  if (!num) return 0;
  if (!asnIndex.has(num)) { asnIndex.set(num, asnList.length); asnList.push([num, name]); }
  return asnIndex.get(num);
};

const c4 = table(read("server-country-ipv4-num.csv"), false, ccOf);
const c6 = table(read("server-country-ipv6-num.csv"), true, ccOf);
const a4 = table(read("iptoasn-asn-ipv4-num.csv"), false, asnOf);
const a6 = table(read("iptoasn-asn-ipv6-num.csv"), true, asnOf);

// Binary layout: a stream of unsigned LEB128 varints.
//   per section: count, then count start deltas, then count values
//   then: asn count, then asn numbers
const parts = [];
const bytes = [];
const varint = (n) => { n = BigInt(n); do { let b = Number(n & 0x7fn); n >>= 7n; if (n) b |= 0x80; bytes.push(b); } while (n); };
function section(t) {
  varint(t.starts.length);
  let prev = 0n;
  for (const s of t.starts) { varint(s - prev); prev = s; }
  for (const v of t.vals) varint(v);
}
section(c4); section(c6); section(a4); section(a6);
varint(asnList.length);
for (const a of asnList) varint(a[0]);
parts.push(Buffer.from(bytes));
const bin = Buffer.concat(parts);
const gz = zlib.gzipSync(bin, { level: 9 });
const names = asnList.map((a) => a[1].replace(/[\u0000-\u001f\\`$]/g, " ")).join("\n");
fs.writeFileSync(path.join(out, "geo.js"),
  "// Generated by tools/build-data.mjs. IP to country (server-country) and IP to ASN (IPtoASN),\n" +
  "// from sapics/ip-location-db, Public Domain Dedication and License v1.0 (PDDL).\n" +
  "window.HL_GEO={built:" + JSON.stringify(today) + ",cc:" + JSON.stringify(ccList) +
  ",bin:\"" + gz.toString("base64") + "\",names:" + JSON.stringify(names) + "};\n");

// ---------- Threat lists (CIDR, IPv4) ----------
function cidrs(text) {
  const outRanges = [];
  for (let line of text.split("\n")) {
    line = line.trim();
    if (!line || line[0] === "#") continue;
    const m = line.match(/^(\d+)\.(\d+)\.(\d+)\.(\d+)(?:\/(\d+))?$/);
    if (!m) continue;
    const ip = ((+m[1] << 24) >>> 0) + (+m[2] << 16) + (+m[3] << 8) + +m[4];
    const bits = m[5] === undefined ? 32 : +m[5];
    const size = 2 ** (32 - bits);
    outRanges.push([ip, ip + size - 1]);
  }
  return outRanges.sort((a, b) => a[0] - b[0]);
}
const lists = {};
if (has("firehol_level1.netset")) lists.firehol = { name: "FireHOL level 1", ranges: cidrs(read("firehol_level1.netset")) };
if (has("tor-exits.txt")) lists.tor = { name: "Tor exit node", ranges: cidrs(read("tor-exits.txt")) };
fs.writeFileSync(path.join(out, "threat.js"),
  "// Generated by tools/build-data.mjs. FireHOL level 1 (iplists.firehol.org) and Tor exit list (check.torproject.org).\n" +
  "window.HL_THREAT={built:" + JSON.stringify(today) + ",lists:" + JSON.stringify(lists) + "};\n");

// ---------- World map: SVG paths and centroids per country ----------
const countries = require("i18n-iso-countries");
const world = JSON.parse(fs.readFileSync(require.resolve("world-atlas/countries-110m.json"), "utf8"));
const fc = feature(world, world.objects.countries);
const W = 960, H = 470;
const proj = geoNaturalEarth1().fitExtent([[4, 4], [W - 4, H - 4]], { type: "Sphere" });
const gp = geoPath(proj);
const round = (d) => d.replace(/(\d+\.\d)\d+/g, "$1");
const map = { w: W, h: H, sphere: round(gp({ type: "Sphere" })), c: {} };
for (const f of fc.features) {
  const a2 = countries.numericToAlpha2(f.id) || (f.properties.name === "Kosovo" ? "XK" : null);
  const key2 = a2 || "_" + f.properties.name;
  // Centroid of the largest polygon, so pins land on the mainland (e.g. France, US).
  let main = f;
  if (f.geometry.type === "MultiPolygon") {
    let best = -1;
    for (const poly of f.geometry.coordinates) {
      const g = { type: "Polygon", coordinates: poly }, ar = geoArea(g);
      if (ar > best) { best = ar; main = g; }
    }
  }
  const c = proj(geoCentroid(main));
  map.c[key2] = { n: f.properties.name, d: round(gp(f)), x: Math.round(c[0] * 10) / 10, y: Math.round(c[1] * 10) / 10 };
}
