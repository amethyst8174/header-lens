// Builds the offline data files the dashboard loads from this site.
// Nothing here runs in the browser; the output is static files in /data.
//
// Usage: node tools/build-data.mjs <source-dir>
// <source-dir> must contain:
//   server-country-ipv4-num.csv, server-country-ipv6-num.csv   (sapics/ip-location-db, PDDL)
//   iptoasn-asn-ipv4-num.csv,   iptoasn-asn-ipv6-num.csv       (sapics/ip-location-db, PDDL)
//   firehol_level1.netset                                       (FireHOL, optional)
//   tor-exits.txt                                               (Tor Project, optional)

